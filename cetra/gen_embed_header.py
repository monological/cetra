"""Files of bytes built into a program (spec 14.6): a table of them, `<table>[]` of
CetraEmbeddedFile, declared in a header for the target to include and defined in a source file of
its own, so the bytes are compiled when a file changes and never with the code that reads them. Each
file is given with the name its program reads it by, which becomes an index into the table, so
nothing about the file -- its name, its path, its bytes -- is written anywhere but the build's list."""
import argparse
import os
import re

from gen_shader_header import guard_for, write_if_changed

# Bytes a line of an array holds.
ROW = 16

IDENTIFIER = r'[A-Za-z_][A-Za-z0-9_]*'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('table', help="the table's name, a C identifier: canvas_fonts")
    parser.add_argument('root', help='the source root a file path is told from')
    parser.add_argument('header', help='the header to write')
    parser.add_argument('source', help='the source file to write')
    parser.add_argument('pairs', nargs='+', help='each file as an index name and its path')
    args = parser.parse_args()
    if not re.fullmatch(IDENTIFIER, args.table):
        raise SystemExit(f"{args.table!r} is not a name C can use: a target or a name with a "
                         "character past letters, digits and _")
    if len(args.pairs) % 2:
        raise SystemExit(f"{args.table}: every file wants an index name before it")
    entries = list(zip(args.pairs[0::2], args.pairs[1::2]))
    prefix = args.table.upper()
    indexes, names = {}, {}
    for index, path in entries:
        if not re.fullmatch(IDENTIFIER, index):
            raise SystemExit(f"{args.table}: {index!r} is not a name C can use")
        if index.upper() in indexes:
            raise SystemExit(f"{args.table}: {index} and {indexes[index.upper()]} are one index")
        indexes[index.upper()] = index
        # A font pool keeps a font under its file's name, so two files of one name would be one.
        name = os.path.basename(path)
        if name in names:
            raise SystemExit(f"{args.table}: {path} and {names[name]} are both named {name}")
        names[name] = path
        if os.path.getsize(path) == 0:
            raise SystemExit(f"{args.table}: {path} is empty")
    guard = guard_for(args.header)
    header = [f'// Generated by gen_embed_header.py from the build\'s list: files built into the\n'
              f'// program. Never edit it; change the list.\n'
              f'#ifndef {guard}\n#define {guard}\n\n'
              f'#include "cetra/embedded_file.h"\n\n'
              f'enum {{\n']
    header += [f'    {prefix}_{index.upper()},\n' for index, _ in entries]
    header.append(f'    {prefix}_COUNT\n}};\n\n'
                  f'extern const CetraEmbeddedFile {args.table}[{prefix}_COUNT];\n\n'
                  f'#endif // {guard}\n')
    source = [f'// Generated by gen_embed_header.py from the build\'s list. Never edit it.\n'
              f'#include "{os.path.basename(args.header)}"\n\n']
    for k, (_, path) in enumerate(entries):
        with open(path, 'rb') as f:
            data = f.read()
        rows = (','.join(str(b) for b in data[i:i + ROW]) for i in range(0, len(data), ROW))
        source.append(f'static const unsigned char {args.table}_{k}[] = {{\n'
                      + ',\n'.join(rows) + '\n};\n\n')
    source.append(f'const CetraEmbeddedFile {args.table}[{prefix}_COUNT] = {{\n')
    for k, (index, path) in enumerate(entries):
        rel = os.path.relpath(path, args.root).replace(os.sep, '/')
        source.append(f'    [{prefix}_{index.upper()}] = {{"{os.path.basename(path)}", "{rel}", '
                      f'{args.table}_{k}, sizeof({args.table}_{k})}},\n')
    source.append('};\n')
    # Written only when they changed, so an unchanged list rebuilds nothing.
    write_if_changed(args.header, ''.join(header))
    write_if_changed(args.source, ''.join(source))

if __name__ == '__main__':
    main()
