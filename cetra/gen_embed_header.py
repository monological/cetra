"""Files of bytes built into a program (spec 14.6): a table of them, in one header for the target
alone to include -- a font, so a program is one file with nothing to find beside it. Each file is
given with the name its program reads it by, which becomes an index into the table, so nothing
about the file -- its name, its path, its bytes -- is written anywhere but the build's list."""
import argparse
import os
import re

from gen_shader_header import write_if_changed

# Bytes a line of an array holds.
ROW = 16

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('table', help="the table's name, a C identifier: canvas_fonts")
    parser.add_argument('root', help='the source root a file path is told from')
    parser.add_argument('out', help='the header to write')
    parser.add_argument('pairs', nargs='+', help='each file as an index name and its path')
    args = parser.parse_args()
    if len(args.pairs) % 2:
        raise SystemExit(f"{args.table}: every file wants an index name before it")
    entries = list(zip(args.pairs[0::2], args.pairs[1::2]))
    for index, _ in entries:
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', index):
            raise SystemExit(f"{args.table}: {index!r} is not a name C can use")
    if len({index for index, _ in entries}) != len(entries):
        raise SystemExit(f"{args.table}: an index name is given twice")
    prefix = args.table.upper()
    parts = ['// Generated by gen_embed_header.py from the build\'s list: files built into the\n'
             '// program. Never edit it; change the list.\n'
             '#include <stddef.h>\n\n'
             '#ifndef CETRA_EMBEDDED_FILE\n'
             '#define CETRA_EMBEDDED_FILE\n'
             'typedef struct CetraEmbeddedFile {\n'
             '    const char* name;   // the file\'s own name\n'
             '    const char* source; // the file it was built from, from the source root\n'
             '    const unsigned char* bytes;\n'
             '    size_t size;\n'
             '} CetraEmbeddedFile;\n'
             '#endif\n\n'
             'enum {\n']
    parts += [f'    {prefix}_{index.upper()},\n' for index, _ in entries]
    parts.append(f'    {prefix}_COUNT\n}};\n\n')
    for k, (_, path) in enumerate(entries):
        with open(path, 'rb') as f:
            data = f.read()
        rows = (', '.join(f'0x{b:02x}' for b in data[i:i + ROW]) for i in range(0, len(data), ROW))
        parts.append(f'static const unsigned char {args.table}_{k}[] = {{\n    '
                     + ',\n    '.join(rows) + '\n};\n')
    parts.append(f'\nstatic const CetraEmbeddedFile {args.table}[{prefix}_COUNT] = {{\n')
    for k, (index, path) in enumerate(entries):
        source = os.path.relpath(path, args.root).replace(os.sep, '/')
        size = os.path.getsize(path)
        parts.append(f'    [{prefix}_{index.upper()}] = {{"{os.path.basename(path)}", "{source}", '
                     f'{args.table}_{k}, {size}}},\n')
    parts.append('};\n')
    # Written only when it changed, so an unchanged list rebuilds nothing that includes it.
    write_if_changed(args.out, ''.join(parts))

if __name__ == '__main__':
    main()
